// The TrueU Content Cockpit data model in Airtable. This file is the source of truth for the base
// structure. Apply with `npm run airtable:apply`.
//
// Conventions
// - Every table's first field is its primary field (Airtable shows it as the record name).
// - Status-like fields are single selects whose option names are the codes the app uses
//   (src/lib/status.ts). Renaming an option in Airtable breaks the app: add options instead.
// - "JSON" fields are long text holding JSON written by the app.
// - Record IDs (rec…) are the row IDs. "Created" / "Updated" are set by the app (UTC).
// - Links are declared once; Airtable adds the reverse field in the other table automatically.

