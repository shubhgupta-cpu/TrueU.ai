// ---- field builders
const text = (name, description) => ({ name, type: 'singleLineText', description });
const long = (name, description) => ({ name, type: 'multilineText', description });
const json = (name, description) => ({ name, type: 'multilineText', description: description ? `JSON. ${description}` : 'JSON (written by the app).' });
const url = (name) => ({ name, type: 'url' });
const email = (name) => ({ name, type: 'email' });
const int = (name, description) => ({ name, type: 'number', options: { precision: 0 }, description });
const decimal = (name, precision, description) => ({ name, type: 'number', options: { precision }, description });
const bool = (name, description) => ({ name, type: 'checkbox', options: { icon: 'check', color: 'greenBright' }, description });
const date = (name, description) => ({ name, type: 'date', options: { dateFormat: { name: 'iso' } }, description });
const time = (name, description) => ({
  name,
  type: 'dateTime',
  options: { timeZone: 'utc', dateFormat: { name: 'iso' }, timeFormat: { name: '24hour' } },
  description,
});
const select = (name, values, description) => ({ name, type: 'singleSelect', options: choices(...values), description });
const multi = (name, values, description) => ({ name, type: 'multipleSelects', options: choices(...values), description });

